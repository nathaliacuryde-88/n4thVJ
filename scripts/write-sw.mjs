/*
 * Writes sw.js: the service worker that lets the VJ run with no internet.
 *
 * It is written fresh on every build with the build's own file list baked
 * in, so a new build is a new worker: the browser installs it, fetches the
 * new files in the background, and drops the old ones once it takes over.
 *
 * Two copies, identical, because Pages may serve either way (see
 * write-boot.mjs): dist/sw.js for the built site, and ./sw.js at the
 * repository root for when Pages serves the repository and the bundle lives
 * under dist/. The worker tries both layouts and keeps whichever answers.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { join, relative } from 'node:path';

const ROOT = new URL('../', import.meta.url).pathname;
const DIST = join(ROOT, 'dist');

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full)));
    else out.push(full);
  }
  return out;
}

const files = (await walk(DIST))
  .map((f) => relative(DIST, f).split('\\').join('/'))
  .filter((f) => f !== 'sw.js' && f !== 'index.html')
  .sort();

const template = await readFile(join(ROOT, 'scripts/sw.template.js'), 'utf8');

// The worker's own code counts too: changing it is a new version.
const hash = createHash('sha256').update(template);
for (const f of files) hash.update(f).update(await readFile(join(DIST, f)));
const version = hash.digest('hex').slice(0, 12);
const sw =
  `// Generated by scripts/write-sw.mjs from scripts/sw.template.js. Do not edit.\n` +
  template
    .replace('__VERSION__', version)
    .replace('__FILES__', JSON.stringify(files));

await writeFile(join(DIST, 'sw.js'), sw, 'utf8');
await writeFile(join(ROOT, 'sw.js'), sw, 'utf8');
console.log(`sw.js -> ${version}, ${files.length} files`);
